export const FOOD_DATABASE: FoodDatabaseItem[] = [
  ...PACKAGED_INDIAN_FOODS,
  ...INDIAN_RESTAURANT_FOODS,
  ...BASE_FOOD_DATABASE,
  ...(csvFoodData as FoodDatabaseItem[])
];

export function searchFoodDatabase(query: string, mealFilter?: MealType): FoodDatabaseItem[] {
  let results = FOOD_DATABASE;
  if (mealFilter) {
    results = results.filter(item => item.mealTags.includes(mealFilter) || (mealFilter === 'cheat_meal' && item.isCheatMeal));
  }
  if (!query || query.trim() === '') {
    return results;
  }
  const cleanQuery = query.toLowerCase().trim();
  return results.filter(item => 
    item.name.toLowerCase().includes(cleanQuery) ||
    item.category.toLowerCase().includes(cleanQuery) ||
    (item.brand && item.brand.toLowerCase().includes(cleanQuery)) ||
    (item.restaurant && item.restaurant.toLowerCase().includes(cleanQuery)) ||
    (item.ingredients && item.ingredients.toLowerCase().includes(cleanQuery))
  );
}

export function getRecommendedFoods(mealType: MealType, remainingCalories: number): FoodDatabaseItem[] {
  // Return tailored recommendations matching meal category and calorie constraints
  const pool = FOOD_DATABASE.filter(f => f.mealTags.includes(mealType));
  
  if (mealType === 'cheat_meal') {
    // For cheat meals, show enjoyable treats with calorie info
    return pool.filter(f => f.isCheatMeal).slice(0, 6);
  }

  // Filter items that reasonably fit remaining budget (or nutritious choices)
  const reasonable = pool.filter(f => f.calories <= Math.max(remainingCalories, 250) + 100);
  return reasonable.length > 0 ? reasonable.slice(0, 6) : pool.slice(0, 6);
}
